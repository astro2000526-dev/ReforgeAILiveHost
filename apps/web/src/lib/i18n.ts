// Cookie-driven (no locale routing): the `locale` cookie is read by Server
// Components via lib/locale-server.ts and by the client via LocaleProvider.
// A single flat dictionary keeps Server + Client in sync.

export const LOCALES = ['en', 'zh', 'th'] as const
export type Locale = (typeof LOCALES)[number]
export const DEFAULT_LOCALE: Locale = 'en'

export const LOCALE_LABELS: Record<Locale, string> = {
  en: 'EN',
  zh: '中文',
  th: 'ไทย',
}

export function normalizeLocale(v: string | undefined | null): Locale {
  return (LOCALES as readonly string[]).includes(v ?? '') ? (v as Locale) : DEFAULT_LOCALE
}

